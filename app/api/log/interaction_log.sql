-- Audit table for ZSmart Branch interaction logging (used by app/api/log/route.ts).
--
-- Run this ONCE as / for the app's DB user (the FLEXCUBE_DB_USER the app connects
-- with), then grant INSERT so the app can write. The table is keyed for lookup by
-- tablet SERIAL number, so with many tablets you can filter the trail per device.
--
-- Requires Oracle 12c+ (IDENTITY column). If the app can't write (table missing or
-- no grant), the endpoint falls back to a JSONL file so no audit data is lost.

CREATE TABLE ZSMART_INTERACTION_LOG (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SERIAL      VARCHAR2(80),   -- tablet serial number (the audit key)
  BRANCH      VARCHAR2(40),   -- branch code
  SESSION_ID  VARCHAR2(80),   -- per-visit id
  EVENT_TYPE  VARCHAR2(60),   -- login_success, otp_fail, face_verify_fail, open, click, ...
  LABEL       VARCHAR2(200),  -- event detail (masked account / element label; never a typed value)
  PATH        VARCHAR2(200),
  CLIENT_IP   VARCHAR2(60),   -- captured server-side
  EVENT_TS    VARCHAR2(40),   -- client timestamp (ISO 8601)
  RECV_TS     TIMESTAMP DEFAULT SYSTIMESTAMP  -- server receive time
);

-- Fast per-tablet, time-ordered audit queries.
CREATE INDEX IX_ZINTLOG_SERIAL ON ZSMART_INTERACTION_LOG (SERIAL, RECV_TS);

